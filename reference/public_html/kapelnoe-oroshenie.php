<p>
	 К основным узлам и компонентам капельной оросительной системы относятся:
</p>
<ul>
	<li>Узел водозабора (насос или насосная станция)</li>
	<li>Узел фильтрации</li>
	<li>Узел фертигации (при необходимости применения удобрений)</li>
	<li>Магистральный и разводящий трубопроводы</li>
	<li>Капельные линии</li>
	<li>Соединительные узлы, комплектующие, регуляторы давления</li>
</ul>
