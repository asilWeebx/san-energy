<h2 class="big with-text" id="kaplya"> Капельная лента </h2>
<p>
	 Капельное орошение — это эффективный способ для поддержания влаги в растениях и систематической подачи растворов удобрений прямо в корневую зону культур. Одно из преимуществ капельного орошения заключается в непосредственном поливе самой почвы, а не листовой части растения, оставляя ее сухой — это предотвращает риски развития различного рода болезней.
</p>
<p>
	 Капельное орошение создает условия для контроля и оптимизации влажности почвы, а также сохраняет ее структуру при поливах. Ирригация продлевает время полива растений и предотвращает эрозию почвы и сток питательных веществ. Распределение воды идет только на необходимые точки — это, в свою очередь, приводит к экономии воды и профилактика роста сорняков.
</p>
<p>
	 Капельная лента (или ирригационная лента) — это часть системы капельного орошения. Вода или растворенные в воде питательные вещества распределяются по ленте и проходят через пластиковые капельницы, которые прикреплены снаружи или изнутри.
</p>
<p>
	 Капельные ленты подходят для орошения теплиц, гряд овощей и садов. Расположенные вдоль линии капельницы (на расстоянии 20, 25, 30, 33, 40, 50 см) равномерно распределяют жидкость по орошаемой местности.
</p>
