<h2 class="big with-text">Принцип работы, основные узлы и компоненты </h2>
<div class="blog-img">
</div>
<div class="blog-img" style="text-align: center;">
 <img alt="Общая схема для сайта с разрезом орошение" src="images/8jh50bc5wl3roj8cpcprl0e74hy5jqvq.jpg" height="auto" width="auto" title="Общая схема для сайта с разрезом орошение">
</div>
<p>
 <a title="Искусственные каналы для орошения" href="/solutions/iskusstvennye-kanaly-dlya-orosheniya.php">Водозабор из источника</a> (1) осуществляется при помощи насосной станции (2), которая подает воду на фильтровальную станцию (3), в состав которой могут входить песчаные, гидроциклонные и другие фильтры и их комбинации, необходимые для получения воды приемлемого для орошения качества.
</p>
<p>
	 Очищенная вода поступает в магистральную линию (4), а далее – в разводящий трубопровод (5), который может быть или жесткой трубой из композитного материала, или гибким напорным шлангом LayFlat.
</p>
<p>
	 Разводящий трубопровод доставляет воду к капельным линиям (6).
</p>
<p>
	 Для укладки капельных линий применяется укладчик капельной ленты (7).
</p>
<h2 class="big with-text">Преимущества капельного орошения </h2>
<p>
 <b>Значительная прибавка к урожаю.</b> При сравнении урожайности без орошения и использованием <a title="Промышленный капельный полив культур" href="/solutions/promyshlennyy-kapelnyy-poliv-kultur.php">промышленного капельного орошения</a>, разница может оказаться двукратной. Прирост урожайности при замене существующей системы капельной зависит от качества и точности применяемого метода и в некоторых случаях, как показывает практика, достигает 50%.
</p>
<p>
 <b>Малый расход воды.</b> Снижение потерь воды на инфильтрацию и сток позволяет сократить водозабор на 50% и даже более.
</p>
<p>
 <b>100%-е землепользование.</b> Системы капельного орошения позволяют осуществлять полив любых площадей, в том числе, неправильной формы – без пропусков и мертвых зон.
</p>
 <b>Экономия энергии.</b> Вследствие потребности в небольшом количестве воды (по сравнению с другими методами орошения) и низком давлении применяются насосы меньшей мощности, потребляющие меньше энергии.
<p>
</p>
