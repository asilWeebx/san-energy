		<h2 class="big with-text"> Завод по производству плоскосворачиваемых шлангов (рукавов)</h2>
		<p>
			 ООО "SAN HYDRO ENERGY" — первый в России завод по разработке и производству отечественных плоскосворачиваемых шлангов (рукавов) для различных сфер деятельности, включая МЧС, горнодобывающая промышленность, муниципальные хозяйства и АПК, с 2021 года — резидент особой экономической зоны технико–внедренческого типа «Дубна». Производственный цех оснащен современным оборудованием европейского производства, контроль каждой операции лежит на высококвалифицированных сотрудниках, что в совокупности обеспечивает высокое стабильное качество выпускаемой продукции.
		</p>
		<p>
 <a title="Плоскосворачиваемые шланги компании ООО "SAN HYDRO ENERGY"" href="/#">Плоскосворачиваемые шланги (рукава)</a> производятся по особой технологии, разработанной ООО "SAN HYDRO ENERGY", и не имеют аналогов в России. Инновационная технология позволяет выпускать широкий ассортимент шлангов (рукавов) серийной номенклатуры, а также разрабатывать и производить продукцию с нестандартными характеристиками, учитывая пожелания заказчика в отношении диаметра шланга (рукава), толщины стенок, рабочего и разрывного давления.
		</p>
		<p>
			 Особое внимание уделяется контролю качества исходного сырья на стадии его поступления, проверке каждого метра полуфабриката на каждом этапе производства, а также испытаниям на прочность и герметичность шланга (рукава). Для проведения таких испытаний построена 216–метровая испытательная эстакада, на сегодняшний день являющаяся самой длинной в России, на которой шланг (рукав) разматывается, заполняется водой и подвергается различным проверкам для определения его качества.
		</p>
		<p>
			 На производстве плоскосворачиваемых шлангов (рукавов) оборудована лаборатория, где проводятся дополнительные испытания на соответствие стандартам качества шланга (рукава). Анализ полиэфирной нити на разрыв проводится на разрывной машине, а также проверяется прочность связи внутреннего гидроизоляционного и наружного защитного слоев с каркасом. Шланг (рукав) также проходит испытания на термо– и морозостойкость в специальной климатической камере, где подвергается воздействию низких и высоких температур. Стойкость шланга (рукава) к абразивному износу по ГОСТ 51049–2019 или по ГОСТ 34779–2021 проверяется на единственном в России специальном испытательном стенде. Все результаты испытаний сохраняются в архивах ООО "SAN HYDRO ENERGY".
		</p>
		<p>
			 Только после прохождения всех испытаний шланг (рукав) считается готовым к эксплуатации.
		</p>
		<p>
			 Комплекс уникального лабораторного оборудования, установленный на территории завода, также позволяет проводить сравнительный анализ продукции ООО "SAN HYDRO ENERGY" с продукцией других производителей.
		</p>
		<p>
			 ООО "SAN HYDRO ENERGY" является единственной компанией в России, применяющей собственное лабораторное оборудование для тестирования плоскосворачиваемых шлангов (рукавов).
		</p>
